let _aapEditIdx = null; // null = new, number = editing existing entry

function openAddAlbumModal(editIdx) {
  _aapEditIdx = (editIdx !== undefined) ? editIdx : null;
  const isEdit = _aapEditIdx !== null;
  const entry  = isEdit ? ENTRIES[_aapEditIdx] : null;

  document.getElementById('aap-title').textContent = isEdit ? 'Edit album' : 'Add album';
  document.getElementById('aap-album-title').value = entry ? entry.title  : '';
  document.getElementById('aap-artist').value       = entry ? entry.artist : '';
  document.getElementById('aap-year').value         = entry ? entry.year   : (activeYear || new Date().getFullYear());
  document.getElementById('aap-art').value          = entry ? (entry.art || '') : '';
  document.getElementById('aap-audio').value        = entry ? (entry.audio || '') : '';
  document.getElementById('aap-tagline').value      = entry ? (entry.tagline || '') : '';
  document.getElementById('aap-review').value       = entry ? (entry.review || '') : '';

  _aapUpdateArtPreview(entry ? entry.art : '');

  // Every album here is deletable now - removing one no longer touches the timeline.
  document.getElementById('aap-delete-btn').style.display = isEdit ? '' : 'none';

  document.getElementById('add-album-overlay').style.display = 'block';
  document.getElementById('add-album-panel').style.display   = 'flex';
  document.getElementById('aap-album-title').focus();
}

function closeAddAlbumModal() {
  document.getElementById('add-album-overlay').style.display = 'none';
  document.getElementById('add-album-panel').style.display   = 'none';
  _aapEditIdx = null;
}

function saveAddAlbumModal() {
  const title  = document.getElementById('aap-album-title').value.trim();
  const artist = document.getElementById('aap-artist').value.trim();
  const year   = parseInt(document.getElementById('aap-year').value, 10) || activeYear;
  const art    = document.getElementById('aap-art').value.trim();
  const audio  = document.getElementById('aap-audio').value.trim();
  const tagline = document.getElementById('aap-tagline').value.trim();
  const review  = document.getElementById('aap-review').value.trim();

  if (!title) { document.getElementById('aap-album-title').focus(); return; }

  if (_aapEditIdx !== null) {
    // Editing an existing entry in-place
    const entry = ENTRIES[_aapEditIdx];
    entry.title   = title;
    entry.artist  = artist;
    entry.year    = year;
    entry.art     = art;
    entry.audio   = audio;
    entry.tagline = tagline;
    entry.review  = review;
  } else {
    // A new album belongs to this view alone; era/movement were timeline placement and
    // no longer apply. `review` used to be listed twice here, the second an empty string,
    // so anything typed into the review box when ADDING an album was silently discarded.
    ENTRIES.push({
      type: 'album',
      year,
      title,
      artist,
      tagline,
      art,
      audio,
      tier: '',
      artBg: '#181818',
      artColor: '#999',
      tags: [],
      review,
      context: '',
      tracks: [],
    });
  }

  persist();
  closeAddAlbumModal();
  renderYearNav();
  renderList();
}

function deleteAlbumEntry(entryIdx) {
  const entry = ENTRIES[entryIdx];
  if (!entry) return;
  if (!confirm(`Delete "${entry.title}"?`)) return;
  DELETED_KEYS.add(entryKey(entry));
  ENTRIES.splice(entryIdx, 1);
  persist();
  renderYearNav();
  renderList();
}

function _aapUpdateArtPreview(url) {
  const prev = document.getElementById('aap-art-preview');
  if (!prev) return;
  if (url) {
    prev.innerHTML = `<img src="${url}" onerror="this.parentElement.textContent='🎵'">`;
  } else {
    prev.textContent = '🎵';
  }
}

// This view used to have no export of its own - edits here rode along in the timeline's
// "⬇ data.js" button, because both views shared one array. After the fork that button
// only writes the timeline's entries, so Best of Year needs its own way to disk or its
// albums would live in localStorage and never reach the repo.
function saveBestOfDataJs() {
  const content =
    '// Albums for the Best of Year view (best-of-year.html).\n'
    + '//\n'
    + '// Deliberately separate from data.js: the two views were forked so that an album\n'
    + '// can be deleted, reordered or re-rated in one without touching the other. Albums\n'
    + '// that appear in both timelines exist as independent copies here - editing one side\n'
    + '// does not change the other.\n'
    + 'const BEST_OF_ENTRIES = ' + JSON.stringify(ENTRIES, null, 2) + ';\n'
    // YEAR_NOTES lives in this file too, so it has to be written back out - otherwise one
    // click of this button would silently drop every year summary on the floor.
    + '\n// One-paragraph summary per year, shown under the title on best-of-year.html.\n'
    + '// Written to describe the albums actually on each list, so revisit the text when a\n'
    + "// year's selections change substantially.\n"
    + 'const YEAR_NOTES = ' + JSON.stringify(typeof YEAR_NOTES !== 'undefined' ? YEAR_NOTES : {}, null, 2) + ';\n';

  const blob = new Blob([content], { type: 'text/javascript;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = 'bestof-data.js';
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);

  // Bust the cache on the next deploy, the same way saveDataJs() does for the timeline.
  const v = Date.now();
  fetch('best-of-year.html')
    .then(r => r.text())
    .then(html => {
      const updated = html.replace(/(<script\s+src="bestof-data\.js)(\?v=[^"]*)?(")/, '$1?v=' + v + '$3');
      const b = new Blob([updated], { type: 'text/html;charset=utf-8' });
      const u = URL.createObjectURL(b);
      const link = document.createElement('a');
      link.href = u;
      link.download = 'best-of-year.html';
      document.body.appendChild(link);
      link.click();
      document.body.removeChild(link);
      URL.revokeObjectURL(u);
    })
    .catch(() => {
      console.warn('Could not auto-update best-of-year.html version — update bestof-data.js?v= manually if cache is stale');
    });
}

