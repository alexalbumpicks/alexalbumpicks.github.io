// The imports that landed among these deliberately did NOT bump - the 'addendum' pass (24
// albums into sixteen years already on the site) and the two 'current' passes (26 into 2025 and
// 2026, same shape) - and the distinction is the rule to follow: `additions` and
// backfillEmptyFields below run regardless of version, so albums *added* alongside a save
// arrive either way, while a bump re-takes `audio` for every entry. Bump when baked data the
