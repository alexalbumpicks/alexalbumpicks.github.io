// backfillEmptyFields reaches a blank on its own.
//
// 33 is the line between those two: an album *appended* to a year changes nothing anyone
// already has, an album *inserted* into one renumbers everything under it. Same act from the
// editor's side, opposite answers - what decides it is whether existing entries moved, not
// whether an entry was added.
//
// Those years are likewise absent from RERANKED_YEARS: every one of those imports appended to a
// running order instead of rewriting it, so there is nothing to heal. These bumps cannot disturb
// the order either - every year involved has sat in RERANKED_YEARS since its own import, at 19
// or below, and any save new enough to be affected here is well past that. 33 is the exception
// and is scoped to the one year it renumbered.
const STORAGE_SCHEMA_VERSION = 33;

// Deleting can't just drop the entry from ENTRIES: the loader re-adds anything present
// in bestof-data.js but missing from the saved set (so new imports show up), and a
// deleted entry is exactly that - it would come straight back on reload. Deletes leave a
// tombstone here, and the loader skips additions that carry one.
const DELETED_KEYS = new Set();

// tierLabels - the display names for the badges above each title - lived here until the badges
// were dropped from the card. tierWeight below is a different thing and is still live: it has
// no text, it only orders a year nobody has ranked yet.
const tierWeight = {
  essential: 3,
  pioneer: 2,
  postinfluence: 1,
  influence: 0
};

function stars(n) {
  return [1, 2, 3, 4, 5].map(i => (i <= n ? '★' : '☆')).join('');
}

function albumArt(entry) {
  if (entry.art) {
    return `<img src="${esc(entry.art)}" alt="${esc(entry.title)} album art" loading="lazy">`;
  }

  return `
    <div class="year-art-fallback" style="background:${esc(entry.artBg || '#181818')};color:${esc(entry.artColor || '#999')}">
      <div>${esc(entry.title)}<br><span style="opacity:.65">${esc(entry.artist)}</span></div>
    </div>
  `;
}

function audioEmbedHtml(url) {
  if (!url) return '';
  const sp = url.match(/open\.spotify\.com\/(track|album|playlist|episode)\/([A-Za-z0-9]+)/);
  if (sp) {
    return `<iframe src="https://open.spotify.com/embed/${sp[1]}/${sp[2]}?utm_source=generator" height="152" allow="autoplay; clipboard-write; encrypted-media; fullscreen; picture-in-picture" loading="lazy"></iframe>`;
  }
  const yt = url.match(/(?:youtube\.com\/watch\?v=|youtu\.be\/)([A-Za-z0-9_-]+)/);
  if (yt) {
    return `<a class="year-action" href="${esc(url)}" target="_blank" rel="noopener">Watch on YouTube</a>`;
  }
  if (url.includes('soundcloud.com')) {
    return `<a class="year-action" href="${esc(url)}" target="_blank" rel="noopener">Listen on SoundCloud</a>`;
  }
  if (/\.(mp3|ogg|wav|m4a|aac|flac)(\?|$)/i.test(url)) {
    return `<audio controls><source src="${esc(url)}">Your browser doesn't support audio.</audio>`;
  }
  return `<a class="year-action" href="${esc(url)}" target="_blank" rel="noopener">Open link</a>`;
}

function excerpt(...parts) {
  return parts.find(Boolean) || '';
}

function yearLink(year) {
  return `best-of-year.html?year=${encodeURIComponent(year)}`;
}

function persist() {
  try {
    // Anything back in ENTRIES - re-added by hand, or renamed onto a dead key - must
    // lose its tombstone here, or the next load would delete it all over again.
    ENTRIES.forEach(entry => DELETED_KEYS.delete(entryKey(entry)));
    localStorage.setItem(LS_KEY, JSON.stringify({
      storageSchemaVersion: STORAGE_SCHEMA_VERSION,
      entries: ENTRIES,
      deleted: [...DELETED_KEYS],
    }));
  } catch (e) {
    // Ignore persistence failures in private browsing or quota limits.
  }
}

function entryKey(entry) {
  // Strip accents and punctuation, but keep letters/digits of ANY script - a
  // /[^a-z0-9]/ strip collapses CJK titles to '', making every such album collide.
  const norm = value => String(value || '')
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^\p{L}\p{N}]/gu, '');
  return `${entry.type}|${entry.year}|${norm(entry.title)}|${norm(entry.artist)}`;
}

// A saved copy predating a data.js change keeps its blank fields forever, so an album
// imported before its audio link existed would never grow a Listen button. Only fills
// gaps — anything the user actually typed wins.
function backfillEmptyFields(saved, baked) {
  if (!baked) return saved;
  const blank = value => value === undefined || value === null || value === ''
    || (Array.isArray(value) && !value.length);
  Object.keys(baked).forEach(field => {
    if (blank(saved[field]) && !blank(baked[field])) saved[field] = baked[field];
  });
  return saved;
}

// A saved entry carries its own non-blank `audio`, so it slips past backfillEmptyFields and
// shadows the data file forever — which is why swapping the Spotify embeds for Apple previews
// appeared to do nothing. Every `audio` here came from the import scripts rather than the
// editor, so the baked value is the better source; take it wholesale. Gated on the schema
// version, so this runs once and a link chosen in the editor afterwards is left alone.
// Mirrors the baked value exactly, including *absence* of one: when a link turns out to be
// plain wrong (the wrong band's song) the fix is to clear it, and bailing out on a blank
// baked `audio` would leave the bad link sitting in every saved copy forever.
function healAudioFromBaked(entry, baked) {
  if (!baked) return entry;
  entry.audio = baked.audio || '';
  return entry;
}

// Years whose running order an import established, mapped to the schema version that did it.
// sortedYearAlbums auto-numbers and *persists* a rank for any year you merely look at, so an
// album that sat alone in its year already has `yearRank: 1` saved — non-blank, so
// backfillEmptyFields leaves it alone and it collides with the newly imported album that
// should outrank it. Take the baked rank, but only for these years: elsewhere the order may
// have been set deliberately with the ▲▼ controls.
//
// The *version* half matters as much as the year half. This used to be a bare Set fired from
// the same flag as the audio heal, which goes true on every bump — so versions 10-15, all of
// them audio-only track swaps, each re-took the baked order for 2010-2019 and threw away
// re-ranking done in between. Heal only when the saved copy predates the import that set the
// order. Add years here as each decade lands, with the version that imported it.
const RERANKED_YEARS = new Map([
  ...[2010, 2011, 2012, 2013, 2014, 2015, 2016, 2017, 2018, 2019].map(y => [y, 8]),
  ...[2020, 2021, 2022, 2023, 2024].map(y => [y, 16]),
  ...[1969, 1993, 1994, 1997, 1998].map(y => [y, 17]),
  // Everything else before 2000. Written as the range minus what 17 already claimed rather
  // than as thirty-nine literals - the five above must keep their own version, or a v17 save
  // would have its hand-ranking of those years taken back. 1957 and 1958 have no entries yet
  // and cost nothing to carry.
  ...Array.from({ length: 46 }, (_, i) => 1954 + i)
    .filter(y => ![1969, 1993, 1994, 1997, 1998].includes(y))
    .map(y => [y, 18]),
  [2025, 19],
  // 2026 is at 33, not the 19 its import set, because the order has been rewritten since:
  // L'Rain went in at #7 by hand and pushed fifteen albums down a place. A v32 save holds the
  // pre-insert numbers for all fifteen, so it has to take the baked order or the year carries
  // a duplicate at every rank from 7 down. Raising 2026's version rather than adding a second
  // entry for it keeps the invariant that a year appears once here; 2025 is untouched by the
  // insert and stays at the version that imported it.
  [2026, 33],
]);

// Entries dropped from bestof-data.js that must also go from an existing save. Removing an
// album from the baked list is not enough on its own: the loader replays `saved.entries`
// verbatim, so anything already saved survives its own deletion. DELETED_KEYS is no help
// either - that only suppresses *re-additions*, and there is nothing left to re-add.
//
// Versioned like RERANKED_YEARS, and for the same reason: the purge has to stop firing once
// everyone has passed it, or an entry the editor legitimately re-creates later would keep
// being swept away on every subsequent bump.
const RETIRED_KEYS = new Map([
  // Two blank rows - literally 'Artist' / 'New Album', no art, audio or text - left behind by
  // the editor's add button. 2026 had nothing else in it until this import, so they had never
  // been noticeable before.
  ['album|2026|newalbum|artist', 19],
  // Not a deletion but a rename: Madonna's 2026 album is styled CONFESSIONS II and was
  // imported under the sheet's 'Confessions 2'. Title is part of entryKey, so the renamed
  // entry is a different album as far as the loader is concerned - `additions` brings in
  // CONFESSIONS II and the old row, which nothing now matches, would sit there beside it.
  // Retiring the old key is what makes a rename one album rather than two.
  ['album|2026|confessions2|madonna', 32],
]);

function dropRetired(entries, savedVersion) {
  return entries.filter(entry => {
    const since = RETIRED_KEYS.get(entryKey(entry));
    return since === undefined || savedVersion >= since;
  });
}

function healYearRankFromBaked(entry, baked, savedVersion) {
  const since = RERANKED_YEARS.get(entry.year);
  if (!baked || since === undefined || savedVersion >= since) return entry;
  if (Number.isFinite(baked.yearRank)) entry.yearRank = baked.yearRank;
  return entry;
}

// Albums whose `art` was pointing at the wrong record and has since been corrected by hand,
// mapped to the schema version that corrected it. The bump re-takes `audio` for everything,
// but not `art`: cover images can be set deliberately in the editor, and taking the baked one
// wholesale would silently undo that. So art is healed only for the keys named here, and -
// as with RERANKED_YEARS - only for saves older than the fix, or a later unrelated bump would
// keep overwriting a cover chosen in the editor afterwards. Add a key whenever an `art` URL
// is fixed by hand, with the version that fixed it; drop it once it's long shipped.
const REHEAL_ART_KEYS = new Map([
  // Resolved to some other release entirely - neither the cover nor the preview belonged
  // to the 2016 Avalanches record.
  ['album|2016|wildflower|theavalanches', 11],
]);

function healArtFromBaked(entry, baked, savedVersion) {
  const since = REHEAL_ART_KEYS.get(entryKey(entry));
  if (!baked || since === undefined || savedVersion >= since) return entry;
  if (baked.art) entry.art = baked.art;
  return entry;
}

// `rating` is the one field the editor owns outright, so there is no general heal for it -
// re-taking it wholesale would wipe every star set by hand. It still needs a way through for
// one case: an album added here rather than imported arrives carrying the unscored placeholder
// of 3, and a saved copy that has already picked that up keeps it forever, because
// backfillEmptyFields only fills blanks and 3 is not blank. Same shape as REHEAL_ART_KEYS -
// name the entry and the version that corrected it, and no other rating anywhere moves.
const REHEAL_RATING_KEYS = new Map([
  // Added at 26 on the unscored default, scored by hand two versions later.
  ['album|2011|letenglandshake|pjharvey', 28],
]);

function healRatingFromBaked(entry, baked, savedVersion) {
  const since = REHEAL_RATING_KEYS.get(entryKey(entry));
  if (!baked || since === undefined || savedVersion >= since) return entry;
  if (baked.rating) entry.rating = baked.rating;
  return entry;
}

// Before the fork both views shared one localStorage blob, so a reader arriving with
// edits made under the old scheme has all their year orderings, ratings and reviews
// sitting in the timeline's key. Claim a copy once, rather than silently resetting this
// page to the baked-in order. The timeline's blob is left untouched - it still needs it.
function migrateFromSharedStore() {
  try {
    if (localStorage.getItem(LS_KEY)) return null;   // already forked, nothing to do
    const raw = localStorage.getItem(LEGACY_LS_KEY);
    if (!raw) return null;
    const legacy = JSON.parse(raw);
    if (!Array.isArray(legacy.entries) || !legacy.entries.length) return null;
    const mine = legacy.entries.filter(e => e.type === 'album' && !e.hideFromBestOfYear);
    if (!mine.length) return null;
    // hideFromBestOfYear / bestOfYearOnly no longer route anything; the file an entry
    // lives in is what decides which view shows it.
    mine.forEach(e => { delete e.bestOfYearOnly; delete e.hideFromBestOfYear; });
    const migrated = { entries: mine, deleted: Array.isArray(legacy.deleted) ? legacy.deleted : [] };
    localStorage.setItem(LS_KEY, JSON.stringify(migrated));
    return migrated;
  } catch (e) {
    return null;   // corrupted legacy data - fall back to the baked-in albums
  }
}

function loadPersistedEntries() {
  try {
    migrateFromSharedStore();
    const raw = localStorage.getItem(LS_KEY);
    if (!raw) return;
    const saved = JSON.parse(raw);
    if (Array.isArray(saved.deleted)) saved.deleted.forEach(key => DELETED_KEYS.add(key));
    if (!Array.isArray(saved.entries) || !saved.entries.length) return;
    // Saved entries win, but albums added to data.js since the last save still need to
    // show up — otherwise a stale localStorage copy hides every new import. Albums the
    // user deleted are the one exception: they stay gone.
    const savedEntries = dropRetired(saved.entries, saved.storageSchemaVersion || 0);
    const savedKeys = new Set(savedEntries.map(entryKey));
    const additions = ENTRIES.filter(entry => !savedKeys.has(entryKey(entry))
      && !DELETED_KEYS.has(entryKey(entry)));
    const baked = new Map(ENTRIES.map(entry => [entryKey(entry), entry]));
    const savedVersion = saved.storageSchemaVersion || 0;
    const healAudio = savedVersion < STORAGE_SCHEMA_VERSION;
    ENTRIES.length = 0;
    savedEntries.forEach(entry => {
      const twin = baked.get(entryKey(entry));
      let next = backfillEmptyFields(entry, twin);
      if (healAudio) {
        // Audio is re-taken on every bump by design; rank and art carry their own
        // thresholds so an unrelated bump can't undo work done in the editor.
        next = healAudioFromBaked(next, twin);
        next = healArtFromBaked(next, twin, savedVersion);
        next = healRatingFromBaked(next, twin, savedVersion);
        next = healYearRankFromBaked(next, twin, savedVersion);
      }
      ENTRIES.push(next);
    });
    additions.forEach(entry => ENTRIES.push(entry));
    if (healAudio || additions.length) persist();
  } catch (e) {
    // Ignore corrupted local data and fall back to baked-in entries.
  }
}

function compareDefaultYearOrder(a, b) {
  const ratingDiff = (b.entry.rating || 0) - (a.entry.rating || 0);
  if (ratingDiff !== 0) return ratingDiff;

  const tierDiff = (tierWeight[b.entry.tier] || 0) - (tierWeight[a.entry.tier] || 0);
  if (tierDiff !== 0) return tierDiff;

  return a.idx - b.idx;
}

function allAlbums() {
  return ENTRIES
    .map((entry, idx) => ({ entry, idx }))
    // Every album in this store belongs to this view - routing flags are gone.
    .filter(({ entry }) => entry.type === 'album' && Number.isFinite(entry.year));
}

function sortedYearAlbums(year) {
  const albums = allAlbums().filter(({ entry }) => entry.year === year);
  const ranked = albums.every(({ entry }) => Number.isFinite(entry.yearRank));
  const sorted = albums.slice().sort((a, b) => {
    if (Number.isFinite(a.entry.yearRank) || Number.isFinite(b.entry.yearRank)) {
      if (!Number.isFinite(a.entry.yearRank)) return 1;
      if (!Number.isFinite(b.entry.yearRank)) return -1;
      if (a.entry.yearRank !== b.entry.yearRank) return a.entry.yearRank - b.entry.yearRank;
    }
    return compareDefaultYearOrder(a, b);
  });

  if (!ranked && sorted.length) {
    sorted.forEach(({ entry }, i) => {
      entry.yearRank = i + 1;
    });
    persist();
  }

  return sorted;
}

